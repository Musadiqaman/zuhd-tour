import express from 'express';
import { getDashboard } from '../controllers/dashboardController.js';
import { listPosts, getPost, createPost, updatePost, changePostStatus, deletePost } from '../controllers/postsController.js';
import { uploadImage, listImages, deleteImage } from '../controllers/mediaController.js';
import { getSettings, updateSettings } from '../controllers/settingsController.js';
import { reviewStatus } from '../controllers/reviewsController.js';
import { requireAuth, csrf } from '../middlewares/auth.js';
import { writeLimiter, limited, cookieNoStore } from '../middlewares/rateLimit.js';
import { upload } from '../middlewares/upload.js';
const router = express.Router();
router.use(cookieNoStore, requireAuth, csrf, writeLimiter);
router.get('/dashboard', getDashboard);
router.get('/posts', listPosts);
router.get('/posts/:id', getPost);
router.post('/posts', createPost);
router.put('/posts/:id', updatePost);
router.patch('/posts/:id/status', changePostStatus);
router.delete('/posts/:id', deletePost);
router.post('/media', limited(60, 60 * 60 * 1000), upload.single('image'), uploadImage);
router.get('/media', listImages);
router.delete('/media/:id', deleteImage);
router.get('/settings', getSettings);
router.put('/settings', updateSettings);
router.get('/reviews', reviewStatus);
export default router;
